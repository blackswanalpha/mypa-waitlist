#!/usr/bin/env node
/**
 * Builds the two static inputs of the phone field's country picker.
 *
 *   public/flags/<ISO>.svg   one 3:2 flag per region libphonenumber-js knows,
 *                            copied from the MIT country-flag-icons set, so a
 *                            flag is an <img> fetched on demand, never JS.
 *   lib/phone/timezones.ts   IANA timezone → ISO region, read from tzdata's
 *                            zone.tab, which the picker uses to guess where a
 *                            visitor is before they choose.
 *
 * Re-run after bumping either package or the system tzdata:
 *   node scripts/build-phone-data.mjs
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const { getCountries } = require("libphonenumber-js/min");

const regions = getCountries();

// Flags.
const src = join(dirname(require.resolve("country-flag-icons/package.json")), "3x2");
const out = join(root, "public", "flags");
mkdirSync(out, { recursive: true });
copyFileSync(join(src, "..", "LICENSE"), join(out, "LICENSE"));
const missing = [];
for (const r of regions) {
  const from = join(src, `${r}.svg`);
  if (existsSync(from)) copyFileSync(from, join(out, `${r}.svg`));
  else missing.push(r);
}

// Timezones.
const zoneTab = process.env.ZONE_TAB ?? "/usr/share/zoneinfo/zone.tab";
const version = (() => {
  try {
    return readFileSync("/usr/share/zoneinfo/tzdata.zi", "utf8").split("\n")[0].replace(/^#\s*version\s*/, "");
  } catch {
    return "unknown";
  }
})();
const known = new Set(regions);
const zones = {};
for (const line of readFileSync(zoneTab, "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [cc, , tz] = line.split("\t");
  if (known.has(cc)) zones[tz] = cc;
}
// Legacy names some browsers still report (ICU keeps the old spellings).
const legacy = {
  "Asia/Calcutta": "IN",
  "Asia/Katmandu": "NP",
  "Asia/Saigon": "VN",
  "Asia/Rangoon": "MM",
  "Asia/Dacca": "BD",
  "Asia/Thimbu": "BT",
  "Asia/Macao": "MO",
  "Asia/Ujung_Pandang": "ID",
  "Africa/Asmera": "ER",
  "Atlantic/Faeroe": "FO",
  "Europe/Kiev": "UA",
  "America/Buenos_Aires": "AR",
  "America/Godthab": "GL",
  "America/Indianapolis": "US",
  "America/Louisville": "US",
  "Pacific/Truk": "FM",
  "Pacific/Ponape": "FM",
  "Pacific/Enderbury": "KI",
};
for (const [tz, cc] of Object.entries(legacy)) zones[tz] ??= cc;

const body = Object.keys(zones)
  .sort()
  .map((tz) => `  "${tz}": "${zones[tz]}",`)
  .join("\n");
mkdirSync(join(root, "lib", "phone"), { recursive: true });
writeFileSync(
  join(root, "lib", "phone", "timezones.ts"),
  `// Generated by scripts/build-phone-data.mjs from tzdata ${version} zone.tab. Do not edit.\n` +
    `export const TIMEZONE_REGION: Record<string, string> = {\n${body}\n};\n`,
);

console.log(`${regions.length - missing.length} flags, ${Object.keys(zones).length} timezones`);
if (missing.length) console.log(`no flag for: ${missing.join(" ")}`);
